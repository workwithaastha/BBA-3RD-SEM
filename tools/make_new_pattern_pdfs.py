"""NEW-PATTERN question papers as PDFs (75 marks, 2 h): Section A Q1 (a)-(i) nine compulsory short answers of 5 marks, Section B any 1 of 4 x 15, Section C any 1 of 4 x 15.
The same sets as the website's Mock Exam Box (generated by site/js/mockgen.js). Each PDF = the paper in the real layout + model answers.
Usage: python -I tools/make_new_pattern_pdfs.py <subject-id> <Folder/File prefix> [number of sets]   e.g.  hrm HRM 8
Output: MCQ pdf/<prefix>/<prefix>_New_Pattern_Set_N.pdf  (and <prefix>_New_Pattern_Actual.pdf where an actual paper exists)
"""
import json
import re
import subprocess
import sys
from html import escape as e
from pathlib import Path

import pymupdf

ROOT = Path(__file__).resolve().parent.parent
SID, PREFIX = sys.argv[1], sys.argv[2]
COUNT = int(sys.argv[3]) if len(sys.argv) > 3 else 8
META = {"finance": ("BUSINESS FINANCE", "F010301TN"), "hrm": ("HUMAN RESOURCE MANAGEMENT", "F010302TN"), "marketing": ("MARKETING MANAGEMENT", "F010303TN")}
SUBJ, CODE = META[SID]
NODE = r"""
const fs=require('fs'),path=require('path');global.window={};
const html=fs.readFileSync('site/index.html','utf8');
for(const m of html.matchAll(/<script src="((?:data|js)\/[^"]+)"/g)){if(!(m[1].startsWith('data/')||m[1]==='js/examqa.js'||m[1]==='js/mockgen.js'))continue;require(path.resolve('site',m[1]));}
const id=process.argv[1],count=+process.argv[2];
const bank=window.ExamQA.data[id]||[];
const pick=(q)=>({q:q.q,a:q.a});
const sets=window.MockGen.newPatternSets(id,bank,count).map(s=>({name:s.name,secs:s.secs.map(x=>({name:x.name,rule:x.rule,marks:x.marks,sub:!!x.sub,start:x.start||0,qs:x.qs.map(pick)}))}));
const reals=((window.ExamQA.presets||{})[id]||[]).filter(p=>p.id==='newpaper'||/^case/.test(p.id)).reverse();
for(const real of reals){sets.unshift({name:real.id==='newpaper'?'Actual':'Case Set '+real.id.slice(4),secs:real.real.map(s=>({name:s.name,rule:s.rule,marks:s.marks,sub:!!s.sub,start:s.start||0,qs:s.ids.map(k=>bank.find(x=>x.put===k)).filter(Boolean).map(pick)}))});}
console.log(JSON.stringify(sets));
"""
raw = subprocess.run(["node", "-e", NODE, SID, str(COUNT)], cwd=ROOT, capture_output=True, text=True, encoding="utf-8")
sets = json.loads(raw.stdout)
OUT = ROOT / "MCQ pdf" / PREFIX
OUT.mkdir(parents=True, exist_ok=True)
CSS = """
body{font-family:serif;font-size:11pt;line-height:1.4}
h2{font-size:12.5pt;color:#4338ca;margin:12pt 0 3pt;font-family:sans-serif}
h3{font-size:11pt;color:#4c1d95;margin:9pt 0 2pt;font-family:sans-serif}
h4{font-size:10pt;color:#334155;margin:7pt 0 2pt;font-family:sans-serif}
p{margin:2pt 0}
.c{text-align:center}
.code{text-align:right;font-weight:bold}
.sec{text-align:center;font-size:12pt;font-weight:bold;margin:12pt 0 0 0}
.sty{text-align:center;font-weight:bold;margin:0}
.note{margin:3pt 0 6pt 0}
.q{margin:5pt 0 5pt 22pt}
table{border-collapse:collapse;margin:3pt 0;font-family:sans-serif}
th{border:1px solid #94a3b8;padding:3pt 5pt;text-align:left;font-size:9pt}
td{border:1px solid #cbd5e1;padding:3pt 5pt;font-size:9pt;vertical-align:top}
.part{font-size:16pt;font-weight:bold;color:#0f766e;border-bottom:2px solid #0f766e;margin:0 0 6pt 0;font-family:sans-serif}
ul,ol{margin:2pt 0 3pt 0}
li{margin:1pt 0}
.box{border-left:3px solid #6366f1;padding:2pt 0 2pt 8pt;margin:6pt 0;font-family:sans-serif;font-size:10pt}
"""
W = pymupdf.paper_rect("a4")


def plain(h):
    return re.sub(r"<[^>]+>", "", h)


def label(sec, i, n):
    if sec["sub"]:
        return "(" + "abcdefghi"[i] + ")"
    return str(sec["start"] + i) + "." if sec["start"] else str(n) + "."


def paper_html(s, title):
    h = [f"<p class='code'>{CODE}</p><p class='c'><b>BBA (III Semester)<br>(NEP) Examination, 2026-27<br>{SUBJ}</b></p><p class='c'><i>({title} - practice paper in the real layout, not an official paper)</i></p>",
         "<table width='100%'><tr><td><i>Time : Two Hours</i></td><td style='text-align:right'><i>[Maximum Marks : 75]</i></td></tr></table>",
         "<p class='note'><b>Note :</b> Attempt questions from <b>all</b> sections as directed.</p>",
         "<p class='note'><b>Inst.:</b> The candidates are required to answer only in serial order. If there are many parts of a question, answer them in continuation.</p>"]
    n = 0
    for sec in s["secs"]:
        kind = "Short Answer Type Questions" if sec["sub"] else "Long Answer Type Questions"
        letter = sec["name"].split(" ")[1]
        h.append(f"<p class='sec'>Section - {letter}</p><p class='sty'>({kind})</p>")
        if sec["sub"]:
            h.append("<p class='note'><b>Note :</b> Attempt <b>all</b> questions. Each question carries <b>5</b> marks. &nbsp; 9&times;5=45</p><p>1.</p>")
        else:
            h.append("<p class='note'><b>Note :</b> Attempt any <b>one</b> question. Each question carries <b>15</b> marks. &nbsp; 1&times;15=15</p>")
        for i, q in enumerate(sec["qs"]):
            n += 1
            h.append(f"<p class='q'>{label(sec, i, n + 1)} &nbsp;{q['q']}</p>")
    return "".join(h)


def answers_html(s):
    out = ["<p class='part' style='page-break-before:always'>Model answers</p><div class='box'>Write each answer in your own words first, then compare. Numericals: formula, substitution, final answer with Rs. Section A parts carry 5 marks (about 150 words); Section B and C questions carry 15 marks (about 500-600 words).</div>"]
    n = 0
    for sec in s["secs"]:
        out.append(f"<h2>{e(sec['name'])}</h2>")
        for i, q in enumerate(sec["qs"]):
            n += 1
            a = re.sub(r"<svg.*?</svg>", "<p><i>[Draw the diagram / curve as in the website answer.]</i></p>", q["a"], flags=re.S)
            lab = ("Q1" + label(sec, i, n)) if sec["sub"] else "Q" + label(sec, i, n + 1).rstrip(".")
            out.append(f"<h3>{lab}  {plain(q['q'])} [{sec['marks']} marks]</h3>{a}")
    return "".join(out)


def render(html, out, footer):
    tmp = out.with_suffix(".tmp.pdf")
    story = pymupdf.Story(html="<html><body>" + html + "</body></html>", user_css=CSS)
    wr = pymupdf.DocumentWriter(str(tmp))
    more = 1
    while more:
        dev = wr.begin_page(W)
        more, _ = story.place(W + (40, 44, -40, -44))
        story.draw(dev)
        wr.end_page()
    wr.close()
    d = pymupdf.open(tmp)
    for i, pg in enumerate(d, 1):
        pg.insert_text((W.width / 2 - 70, W.height - 22), f"{footer} - page {i}/{len(d)}", fontsize=8, color=(0.4, 0.4, 0.4))
    d.save(str(out), garbage=3, deflate=True)
    pages = len(d)
    d.close()
    try:
        tmp.unlink()
    except OSError:
        pass
    return pages


for s in sets:
    actual = s["name"] == "Actual"
    name = f"{PREFIX}_New_Pattern_Actual" if actual else f"{PREFIX}_" + s["name"].replace(" ", "_")
    title = "Actual paper 23 Nov 2026" if actual else s["name"]
    pages = render(paper_html(s, title) + answers_html(s), OUT / (name + ".pdf"), f"{SUBJ.title()} - {title}")
    print(name + ".pdf", pages, "pages,", sum(len(x["qs"]) for x in s["secs"]), "questions")
