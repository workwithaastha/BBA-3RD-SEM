"""Build site/data/put-be.js and site/data/put-om.js from tools/data_put_be.py / data_put_om.py (the PUT paper photos in PUT/).
Run: python -I tools/build_put.py   - adds a 'PUT Paper' unit (100 MCQs each, original option order, tagged 'PUT paper') to Business Environment and Office Management.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import data_put_be  # noqa: E402
import data_put_om  # noqa: E402

SETS = [
    ("business-env", data_put_be.BE, data_put_be.TOPICS, "put-be.js", "PUT paper - Business Environment (Allenhouse)"),
    ("office-mgmt", data_put_om.OM, data_put_om.TOPICS, "put-om.js", "PUT paper - Office Automation (Allenhouse)"),
]
for sid, rows, topics, fname, tag in SETS:
    assert len(rows) == 100, (sid, len(rows))
    out = []
    for i, (q, opts, a, why) in enumerate(rows, 1):
        assert len(opts) == 4 and len(set(opts)) == 4 and 0 <= a < 4, (sid, i)
        t = next(name for lo, hi, name in topics if lo <= i <= hi)
        out.append({"u": "PUT Paper", "t": t, "n": 1000 + i, "q": q, "o": opts, "a": a, "e": why, "p": tag})
    data = json.dumps(out, ensure_ascii=False, separators=(",", ":"))
    js = ("// Generated by tools/build_put.py from the PUT paper photos (PUT/ folder). Do not edit by hand.\n"
          f"window.SUBJECTS['{sid}'].mcqs.push(...{data});\n")
    (ROOT / "site" / "data" / fname).write_text(js, encoding="utf-8")
    spread = [sum(1 for x in out if x["a"] == k) for k in range(4)]
    print(sid, len(out), "answer spread", spread)
