"""Build site/data/finance-new-mcq.js from tools/data_fin_new.py: new Business Finance MCQs for the 4-unit syllabus (n = 2001..., options shuffled with a fixed seed,
a reason for the correct option and for every wrong option). Run: python -I tools/build_fin_new_mcq.py"""
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from data_fin_new import RAW  # noqa: E402

try:  # drop a question already on the site (same text)
    existing = set()
    import re
    for f in ("finance.js", "finance-mcq.js"):
        existing |= set(re.findall(r'"q":"([^"]+)"', (ROOT / "site/data" / f).read_text(encoding="utf-8")))
except OSError:
    existing = set()
rnd = random.Random(2026)
out, seen = [], set()
for i, (u, t, q, c, w1, w2, w3, why, r1, r2, r3) in enumerate(RAW, 1):
    opts = [c, w1, w2, w3]
    assert len(set(opts)) == 4, q
    assert q not in seen, q
    seen.add(q)
    if q in existing:
        continue
    order = list(range(4))
    rnd.shuffle(order)
    reasons = [r1, r2, r3]
    item = {"u": u, "t": t, "n": 2000 + i, "q": q, "o": [opts[k] for k in order], "a": order.index(0), "e": why, "w": ["" if order[k] == 0 else reasons[order[k] - 1] for k in range(4)], "g": 1}
    out.append(item)
js = ("// Generated by tools/build_fin_new_mcq.py from tools/data_fin_new.py - do not edit by hand.\n"
      "window.SUBJECTS['finance'].mcqs.push(..." + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ");\n")
(ROOT / "site/data/finance-new-mcq.js").write_text(js, encoding="utf-8")
per = {}
for x in out:
    per[x["u"]] = per.get(x["u"], 0) + 1
print("finance-new-mcq.js:", len(out), per, "answer spread", [sum(1 for x in out if x["a"] == k) for k in range(4)])
