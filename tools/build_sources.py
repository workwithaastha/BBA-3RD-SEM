"""List the source files (PDF / PPT / DOC ...) of every subject folder -> site/data/sources.js
Adds size, page count (PDF), and flags exact duplicates (same MD5). Run after adding or renaming files:
    python -I tools/build_sources.py
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "site" / "data" / "sources.js"
FOLDERS = {
    "finance": "FINANCE",
    "marketing": "MARKETING",
    "business-env": "BUSINESS ENV",
    "hrm": "HRM",
    "office-mgmt": "OFFICE MANG",
    "physical-education": "Physical Education",
}
EXT = {".pdf", ".ppt", ".pptx", ".doc", ".docx", ".xls", ".xlsx", ".txt", ".png", ".jpg", ".jpeg"}

try:
    import pymupdf
except ImportError:  # page counts are optional
    pymupdf = None


def pages(p):
    if p.suffix.lower() != ".pdf" or pymupdf is None:
        return 0
    try:
        with pymupdf.open(p) as d:
            return len(d)
    except Exception:
        return 0


def content_key(p):
    """MD5 of the file bytes; for PDFs also of the extracted text (catches re-exported copies with identical text)."""
    keys = [hashlib.md5(p.read_bytes()).hexdigest()]
    if p.suffix.lower() == ".pdf" and pymupdf is not None:
        try:
            with pymupdf.open(p) as d:
                txt = " ".join(" ".join(pg.get_text().split()) for pg in d)
            if len(txt) > 300:
                keys.append("t:" + hashlib.md5(txt.encode("utf-8")).hexdigest())
        except Exception:
            pass
    return keys


def main():
    data = {}
    for sid, folder in FOLDERS.items():
        files = sorted([p for p in (ROOT / folder).iterdir() if p.is_file() and p.suffix.lower() in EXT], key=lambda p: p.name.lower())
        seen = {}
        rows = []
        for p in files:
            keys = content_key(p)
            row = {"f": p.name, "kb": round(p.stat().st_size / 1024), "p": pages(p)}
            hit = next((seen[k] for k in keys if k in seen), None)
            if hit:
                row["dup"] = hit
            else:
                for k in keys:
                    seen[k] = p.name
            rows.append(row)
        data[sid] = {"dir": folder, "files": rows}
        print(sid, folder, len(rows), "files", sum(1 for r in rows if "dup" in r), "duplicates")
    js = "// Generated by tools/build_sources.py - do not edit by hand.\nwindow.SOURCES = " + json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n"
    OUT.write_text(js, encoding="utf-8")


main()
