"""Generate site/data/finance-notes2.js (the new 'complete notes' pages, one per unit) from tools/fin_study_content1.py and fin_study_content2.py.
Run: python -I tools/build_fin_site_notes.py   (keeps the website and the PDFs in step - same text)
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
from fin_study_content1 import UNIT1, UNIT2  # noqa: E402
from fin_study_content2 import UNIT3, UNIT4  # noqa: E402

SHORT = {"UNIT I": "finance functions, objectives, TVM, annuity, bonds", "UNIT II": "capital budgeting techniques", "UNIT III": "capital structure, leverage, cost of capital", "UNIT IV": "dividend models, working capital"}
pages = []
for i, (ul, title, lect, topics) in enumerate([UNIT1, UNIT2, UNIT3, UNIT4], 1):
    html = f"<div class='box'><b>{ul} - {title} ({lect.split(' - ')[0]}).</b> Complete notes with formulas and worked examples, written for the new syllabus (Syllabus image FINANCE/syllabus.jpeg) from your Complete Notes file, unit slides and Unit 1-3 notes.</div>"
    for h, body in topics:
        html += f"<h2>{h}</h2>{body}"
    html += (f"<div class='nextsteps'><span>Next steps - Unit {i}</span><a class='nbtn' href='#/finance/qa'>✍️ Detailed written answers</a>"
             "<a class='nbtn' href='#/finance/quiz'>▶ Practise MCQs</a><a class='nbtn' href='#/finance/formulas'>🧮 Formula sheet</a></div>")
    unit_name = ul.replace("UNIT ", "Unit ")
    label = f"{unit_name} · Complete notes" if i == 4 else f"{unit_name}-B · Complete notes"
    pages.append({"id": f"u{i}-new", "title": f"{label} - {SHORT[ul]}", "html": html})
js = ("// Generated by tools/build_fin_site_notes.py from tools/fin_study_content*.py - do not edit by hand.\n"
      "(function () {\n  const SUB = window.SUBJECTS && window.SUBJECTS.finance;\n  if (!SUB) return;\n  const pages = " + json.dumps(pages, ensure_ascii=False) + ";\n"
      "  pages.forEach((p) => { SUB.units.push(p); });\n})();\n")
(ROOT / "site" / "data" / "finance-notes2.js").write_text(js, encoding="utf-8")
print("finance-notes2.js:", len(pages), "pages,", sum(len(p["html"]) for p in pages), "chars")
